function dispose_job(job_id::AbstractString)::Bool
    task = ensure_app_task_exists()
    index = get_job_index(job_id)
    if index >= 1
        job = task.session.jobs[index]
        if is_running(job)
            stop(job)
        end
        deleteat!(task.session.jobs, index)
        return true
    end
    return false
end

