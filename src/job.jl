function rerun_fragments(job::AsyncJob)::Nothing
    if isempty(job.fragments)
        return nothing
    end

    if job.rerun_progress_snapshot == 0
        elapsed_time = time() - job.last_rerun_request
        if elapsed_time >= 0.4
            job.rerun_cooldown = false
            job.rerun_progress_snapshot = length(job.progress_snapshots)
            job.ran_fragments = String[]
            job.last_rerun_request = time()
            rerun_fragments(job.session.client_id, job.fragments)
        elseif !job.rerun_cooldown
            Threads.@spawn begin
                sleep(0.4 - elapsed_time)
                rerun_fragments(job)
                job.rerun_cooldown = false
            end
            job.rerun_cooldown = true
        end
    end
    return nothing
end

"""
# set\\_progress

Reports the progress of the job it is called from.

Every call reruns the fragments bound to the job, so the interface can display
the new progress. To avoid overloading the app, these reruns happen at most
once every 0.4 seconds.

This is also how jobs are stopped: if a stop has been requested with [`stop()`](/docs/version/latest/api-reference/jobs/stop),
`set_progress()` throws a `JobStopped` exception, which ends the job.

### Function Signature

```julia
