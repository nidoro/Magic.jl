    job         ::AsyncJob,
    progress    ::Real,
    message     ::Union{AbstractString, Nothing}    =nothing,
    data        ::Any                               =nothing
)::ProgressSnapshot
```

 Argument    | Description
:----------- |:-------------
 `job`       | The `AsyncJob` whose progress should be reported. If omitted, the job `set_progress()` is called from is used. Calling it outside a job without this argument throws an `IncorrectUsage` error.
 `progress`  | A `Real` between `0` and `1` specifying the progress of the job.
 `message`   | An optional `String` describing the current progress. If `nothing` (default), the progress percentage is used (for example, `"42%"`).
 `data`      | Optional data of `Any` type to be attached to the progress, which can be retrieved with [`get_progress_data()`](/docs/version/latest/api-reference/jobs/get_progress).

### Return Value

The `ProgressSnapshot` created with the passed values.

### Example

```julia
@job("my_job") do
    files = readdir("data")
    for (i, file) in enumerate(files)
        process(file)
        set_progress(i/length(files), message="Processed \$file")
    end
end
```
"""
function set_progress(job::AsyncJob, progress::Real, message::Union{AbstractString, Nothing}=nothing, data::Any=nothing)::ProgressSnapshot
    if job.stop_requested
        throw(JobStopped(job.id))
    end

    if isnothing(message) message = "$(ceil(Int, Float64(progress)*100))%" end
    progress = ProgressSnapshot(progress, message, data)
    push!(job.progress_snapshots, progress)
    rerun_fragments(job)
    yield()
    return progress
end

function set_progress(progress::Real; message::Union{AbstractString, Nothing}=nothing, data::Any=nothing)::ProgressSnapshot
    job = get_current_job()
    if isnothing(job)
        throw(IncorrectUsage(set_progress))
    end
    return set_progress(job, progress, message, data)
end

